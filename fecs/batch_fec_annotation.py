def _broadcast_annotation_value(value, length, column):
    array = np.asarray(value)
    if array.ndim == 0:
        return np.full(length, array.item())
    array = array.reshape(-1)
    if len(array) != length:
        raise ValueError(
            f"Annotation column {column!r} has {len(array)} values; "
            f"expected {length}."
        )
    return array


def write_annotation_csv(output_path):
    """Write annotations one FEC at a time, then atomically replace the CSV."""
    output_path = Path(output_path)
    temporary_path = output_path.with_name(output_path.name + ".tmp")
    columns = [
        "trans_idxs",
        "dExts",
        "dExts_sum",
        "dLcs",
        "dLcs_sum",
        "states",
        "tdExt_direct",
        "tdLc_direct",
        "fec_id",
    ]
    pd.DataFrame(columns=columns).to_csv(temporary_path, index=False)

    final_signature = annotation_state["stage_signatures"].get(
        "final_extensions"
    )
    for trace_info in manifest["traces"]:
        fec_id = trace_info["fec_id"]
        record = annotation_state["traces"][fec_id]
        if record.get("final_extensions_signature") != final_signature:
            raise RuntimeError(f"FEC {fec_id!r} is not ready for final output.")

        trans_idxs = _array_from_record(record, "trans_idxs", dtype=int)
        if trace_info["curve_type"] == "R":
            trans_idxs = np.flip(trans_idxs)
        length = len(trans_idxs)

        frame = pd.DataFrame({"trans_idxs": trans_idxs})
        for column in columns[1:-1]:
            frame[column] = _broadcast_annotation_value(
                record[column],
                length,
                column,
            )
        frame["fec_id"] = fec_id
        frame.to_csv(
            temporary_path,
            mode="a",
            header=False,
            index=False,
            columns=columns,
        )
        print(f"Wrote annotation data: {fec_id}")
        del frame, trans_idxs

    os.replace(temporary_path, output_path)
    print(f"Saved: {output_path}")


